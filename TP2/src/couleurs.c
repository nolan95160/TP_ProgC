#include <stdio.h>

struct Couleur {
	unsigned char rouge;
	unsigned char vert;
	unsigned char bleu;
	unsigned char alpha;
};

int main(void) {
	struct Couleur couleurs[10] = {
		{0xef, 0x78, 0x12, 0xff},
		{0x2c, 0xc8, 0x64, 0xff},
		{0x35, 0x9a, 0xdc, 0xff},
		{0xff, 0x00, 0x00, 0xff},
		{0x00, 0xff, 0x00, 0xff},
		{0x00, 0x00, 0xff, 0xff},
		{0xff, 0xff, 0x00, 0xff},
		{0xff, 0x00, 0xff, 0xff},
		{0x00, 0xff, 0xff, 0xff},
		{0x80, 0x80, 0x80, 0xff}
	};

	for (int i = 0; i < 10; i++) {
		printf("Couleur %d : R=%u, G=%u, B=%u, A=%u\n",
			   i + 1,
			   couleurs[i].rouge,
			   couleurs[i].vert,
			   couleurs[i].bleu,
			   couleurs[i].alpha);
	}

	return 0;
}
